def create_waste_distribution(history):
    from collections import Counter
    if not history: labels,counts,bar_colors=["No data"],[1],["#142a1e"]
    else:
        ctr=Counter(h["waste_type"] for h in history)
        labels=[k.capitalize() for k in ctr]; counts=list(ctr.values())
        pal=["#3abf8a","#1f8f62","#13744d","#0c5438","#073d27","#032216"]
        bar_colors=pal[:len(labels)]
    fig,ax=plt.subplots(figsize=(6,3.5),facecolor=BG); _style(ax,fig)
    bars=ax.bar(labels,counts,color=bar_colors,edgecolor=BG,linewidth=1.5,width=0.5)
    for bar,cnt in zip(bars,counts):
        if labels[0]!="No data":
            ax.text(bar.get_x()+bar.get_width()/2,bar.get_height()+0.04,str(cnt),
                    ha="center",va="bottom",color=DIM,fontsize=8,fontweight="bold")
    ax.set_title("Scan History Distribution",color=GREEN,fontsize=10,fontweight="bold",pad=8)
    ax.set_ylabel("Count",color=DIM,fontsize=8)
    ax.yaxis.set_major_locator(ticker.MaxNLocator(integer=True))
    ax.grid(axis="y",color=DARK,linewidth=0.5,alpha=0.7)
    for sp in ["top","right"]: ax.spines[sp].set_visible(False)
    plt.tight_layout(); return fig

