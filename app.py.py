def create_confidence_donut(predictions):
    labels=[p["label"].split("-")[0].capitalize() for p in predictions]
    sizes=[p["score"]*100 for p in predictions]
    colors=["#3abf8a","#1f8f62","#13744d","#0c5438","#073d27","#032216"]
    fig,ax=plt.subplots(figsize=(5,4),facecolor=BG); ax.set_facecolor(BG)
    _,texts,autotexts=ax.pie(sizes,labels=labels,colors=colors[:len(labels)],
        autopct="%1.1f%%",startangle=90,pctdistance=0.76,
        wedgeprops=dict(width=0.44,edgecolor=BG,linewidth=2))
    for t in texts: t.set_color(DIM); t.set_fontsize(8)
    for at in autotexts: at.set_color("#fff"); at.set_fontsize(7); at.set_fontweight("bold")
    ax.text(0,0.10,f"{sizes[0]:.1f}%",ha="center",va="center",fontsize=15,fontweight="bold",color=GREEN)
    ax.text(0,-0.18,labels[0],ha="center",va="center",fontsize=8,color=DIM)
    ax.set_title("AI Confidence Breakdown",color=GREEN,fontsize=10,fontweight="bold",pad=10)
    plt.tight_layout(); return fig

def create_eco_gauge(eco_score):
    fig,ax=plt.subplots(figsize=(5,3.5),facecolor=BG); ax.set_facecolor(BG)
    theta_bg=np.linspace(np.pi,0,300)
    ax.plot(np.cos(theta_bg),np.sin(theta_bg),linewidth=18,color="#142a1e",solid_capstyle="round")
    frac=max(0.01,eco_score/100); theta_f=np.linspace(np.pi,np.pi-frac*np.pi,300)
    arc_c=GREEN if eco_score>=70 else "#c8922a" if eco_score>=40 else "#d96a6a"
    ax.plot(np.cos(theta_f),np.sin(theta_f),linewidth=18,color=arc_c,solid_capstyle="round")
    ax.text(0,0.12,str(eco_score),ha="center",va="center",fontsize=30,fontweight="bold",color=arc_c)
    ax.text(0,-0.20,"/100",ha="center",va="center",fontsize=11,color=DIM)
    ax.text(0,-0.50,"ECO SCORE",ha="center",va="center",fontsize=8,color="#5a8a6a",fontweight="bold")
